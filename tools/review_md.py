#!/usr/bin/env python3
"""review_md — derive REVIEW.md (the rules a code reviewer holds a diff to) from the security docs.

The security model is the single source: docs/security.md (the stack jail) and
docs/security-jail-main.md (the login jail). Every row of their "Measures in place" tables carries a
Review column with one sentence saying what a change must not do, and the Accepted risks and Open
sections say what is known and must not be reported as new. This script extracts those into
REVIEW.md for reviewers. It is gitignored and regenerated by lint; nothing is written by hand there.

    tools/review_md.py            rewrite REVIEW.md (run by `devbox run lint`: the rendering validates the doc)
    tools/review_md.py --check    exit 1 if REVIEW.md is missing or stale — for the day the file is
                                  committed because a PR review service must read it from the tree

The tables must keep four cells per row and a non-empty Review cell; a malformed row fails the
check, which is the point — a measure without a review rule is a gap in the model.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
SOURCES = (  # (file, label, lead): the stack jail first — it is the product; the login jail is the mechanism's own
    (HERE / "docs" / "security.md", "", "The stack jail — the one a developer uses."),
    (HERE / "docs" / "security-jail-main.md", "login jail: ", "The login jail (`jail-main`) — the mechanism's own; it sees no client content."),
)
TARGET = HERE / "REVIEW.md"

HEADER = """# Review rules — claude-jail-work

<!-- GENERATED from docs/security.md and docs/security-jail-main.md by tools/review_md.py
(gitignored). Do not edit: change a doc's Review column, Accepted risks or Open sections and run
`devbox run review-md`. -->

The security model is [docs/security.md](docs/security.md) for the stack jail and
[docs/security-jail-main.md](docs/security-jail-main.md) for the login jail: tokens and git are the
boundaries, everything else is scenery. Hold a diff to the rules below. A change that weakens a
boundary is **Important**; style and structure are nits. Do not report the accepted risks or the
open items as new findings.
"""


def bullets(section: str) -> list[str]:
    """The bold lead of every top-level bullet in a section, with its first sentence if the lead has none."""
    joined = re.sub(r"\n  +", " ", section)  # unwrap continuation lines
    out = []
    for m in re.finditer(r"^- \*\*(.+?)\*\*(.*)$", joined, re.M):
        lead, rest = m.group(1).strip(), m.group(2).strip()
        if not lead.endswith((".", "!", "?")):
            first = re.split(r"(?<=[.!?])\s", rest, maxsplit=1)[0]
            lead = (lead + first if first[:1] in ",;:" else f"{lead} {first}").strip()
        out.append(lead)
    return out


def cap(text: str) -> str:
    return text[:1].upper() + text[1:]


def render_doc(doc: str, name: str, label: str, lead: str) -> list[str]:
    """One document's rules: its measure tables as bullets, then its accepted risks and open items."""
    sections = re.split(r"^(?=## )", doc, flags=re.M)
    by_title = {s.split("\n", 1)[0][3:].strip(): s for s in sections if s.startswith("## ")}
    measures = by_title.get("Measures in place")
    if measures is None:
        raise SystemExit(f"{name}: no '## Measures in place' section")
    lines = [f"## {cap(label + 'boundaries a change must not weaken')}", "", lead, ""]
    table = None
    for line in measures.split("\n"):
        if line.startswith("### "):
            table = line[4:].strip()
            lines += [f"### {table}", ""]
        elif line.startswith("| ") and not line.startswith("| Measure"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) != 4:
                raise SystemExit(f"{name} ({table}): a row has {len(cells)} cells, not 4 — pipes inside a cell, or no Review column?\n  {line[:100]}")
            measure, _where, _stops, review = cells
            if not review:
                raise SystemExit(f"{name} ({table}): empty Review cell for: {measure[:80]}")
            lines.append(f"- {review}")
        elif line.startswith("|---") and table and lines[-1] != "":
            pass
        elif line == "" and lines[-1].startswith("- "):
            lines.append("")
    for title, heading in (("Accepted risks", "accepted risks — not findings"), ("Open", "known open items — not findings")):
        section = by_title.get(title)
        if section is None:
            raise SystemExit(f"{name}: no '## {title}' section")
        items = bullets(section)
        lines += ["", f"## {cap(label + heading)}", ""] + ([f"- {b}" for b in items] or ["- (none)"])
    return lines


def render() -> str:
    lines = [HEADER]
    for path, label, lead in SOURCES:
        lines += render_doc(path.read_text(), path.relative_to(HERE).as_posix(), label, lead) + [""]
    lines = [ln for i, ln in enumerate(lines) if not (ln == "" and i and lines[i - 1] == "")]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        current = TARGET.read_text() if TARGET.exists() else ""
        if current != text:
            print("REVIEW.md is stale (or missing) — run: devbox run review-md", file=sys.stderr)
            return 1
        print(f"REVIEW.md is current ({len(text)} bytes)")
        return 0
    TARGET.write_text(text)
    print(f"wrote {TARGET.relative_to(HERE)} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
